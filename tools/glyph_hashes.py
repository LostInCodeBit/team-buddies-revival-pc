"""Catalogue of the game's font letters for runtime/hd_text.cpp (writes runtime/glyph_hashes.inc).

Usage: python -I tools\\glyph_hashes.py <menu dump> <briefing dump> <map dump> <battle dump> > runtime\\glyph_hashes.inc
Each dump is a folder with ram.bin and vram.bin that the game writes with TB_RAM_DUMP=<vblank> (into TB_SHOT_DIR;
skip_intro = false) while TB_INPUT plays the input that reaches the first battle:
  700=start;712=;900=start;912=;1100=start;1112=;1500=cross;1512=;1800=cross;1812=;2100=cross;2112=;2400=start;
  2412=;2700=start;2712=;3000=cross;3012=;3900=cross;3912=;4300=cross;4312=;4700=cross;4712=;5100=cross;5112=;
  5500=cross;5512=   (one string, no line breaks)
Vblanks: 1900 the main menu (fonts A and C in VRAM), 3300 a mission briefing (font B), 4200 the park map where the
mission is chosen (font D), 6600 a battle (the HUD's digits H and I). Only hashes are written, nothing of the
game's data.

Each font is a character map (224 bytes for 0x20..0xFF, glyph numbers) followed by a table of 8-byte glyphs
(u, v, w, h, advance, y offset, 0, 0) in RAM; the texels are 4bpp in a texture page. The hash (FNV-1a 64 over
w, h and the palette indices) must match hd_text.cpp. Style 0: anti-aliased letters (the reconstruction draws
an even dark rim); 1 and 2: letters with a drawn outline 1 or 2 texels wide (the reconstruction keeps it).
"""
import struct
import sys

# SLUS-00869: (name, character map, glyph table, glyphs, page x, page y, letter heights, style, dump)
# Font E of the park map (0x118D84, red-to-yellow letters) is left out: hd_text.cpp only redraws letters in
# shades between two colours.
FONTS = [
    ("A", 0x0D4524, 0x0D4604, 70, 768, 256, (8, 8), 0, 0),
    ("B", 0x0D4854, 0x0D4934, 83, 896, 256, (12, 12), 0, 1),
    ("C", 0x0D4BEC, 0x0D4CCC, 71, 768, 256, (16, 16), 0, 0),
    ("D", 0x1186B4, 0x118794, 71, 832, 256, (1, 16), 1, 2),
    ("H", 0x162FE8, 0x1630C8, 13, 768, 0, (18, 18), 2, 3),  # battle HUD: countdown, ammo, health
    ("I", 0x163150, 0x163230, 12, 768, 0, (10, 10), 1, 3),  # battle HUD: small digits
]


def fnv(values):
    x = 1469598103934665603
    for b in values:
        x = ((x ^ b) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return x


def main():
    dumps = []
    for d in sys.argv[1:5]:
        ram = open(d + "\\ram.bin", "rb").read()
        vram = struct.unpack("<524288H", open(d + "\\vram.bin", "rb").read())
        dumps.append((ram, vram))
    seen = set()
    print("// generated by tools/glyph_hashes.py: {hash, w, h, style} of every letter of the game's fonts")
    for name, cmap, table, count, px, py, heights, style, which in FONTS:
        ram, vram = dumps[which]
        chars = {}
        for c in range(0x20, 0x100):
            chars.setdefault(ram[cmap + c - 0x20], c)
        n = 0
        for g in range(1, count):
            u, v, w, h = ram[table + g * 8: table + g * 8 + 4]
            if w == 0 or not heights[0] <= h <= heights[1] or w > 32 or h > 24 or u + w > 256:
                continue
            idx = [(vram[(py + v + j) * 1024 + px + (u + i) // 4] >> (((u + i) & 3) * 4)) & 15
                   for j in range(h) for i in range(w)]
            if not any(idx):
                sys.exit(f"font {name} glyph {g}: no texels; is the font in this dump's VRAM?")
            hv = fnv([w, h] + idx)
            if hv in seen:
                continue
            seen.add(hv)
            c = chars.get(g)
            label = "?" if c is None else chr(c) if 0x21 <= c < 0x7F and c != 0x5C else f"\\x{c:02X}"
            print(f"{{0x{hv:016X}ull, {w}, {h}, {style}}}, // {name} {label}")
            n += 1
        print(f"// font {name}: {n} letters", file=sys.stderr)


main()
