# release_key.ps1 - the release signing key (ECDSA P-256). The launcher installs an update only when the release's
# SHA256SUMS.txt carries a valid signature by this key (SHA256SUMS.txt.sig, made by tools/sign_release.ps1).
# The private key stays on the maintainer's PC, readable by that Windows user only: by default
# %USERPROFILE%\.team-buddies\release-signing.key (TB_RELEASE_KEY or -KeyFile pick another file). Back it up
# offline: without it the launcher cannot install later releases (players would update by hand once, to a
# launcher with a new key).
# Makes the key if there is none (it never replaces one) and writes its public half to launcher/release_key.inc,
# which is compiled into the launcher. Prints paths only, never the key.
# Usage: tools\release_key.ps1 [-KeyFile <path>]
param(
    [string]$KeyFile = $(if ($env:TB_RELEASE_KEY) { $env:TB_RELEASE_KEY } else { Join-Path $env:USERPROFILE ".team-buddies\release-signing.key" }),
    [string]$IncFile = (Join-Path (Split-Path $PSScriptRoot) "launcher\release_key.inc")
)
$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.Core
$fmt = [System.Security.Cryptography.CngKeyBlobFormat]
if (Test-Path $KeyFile) {
    $key = [System.Security.Cryptography.CngKey]::Import([IO.File]::ReadAllBytes($KeyFile), $fmt::EccPrivateBlob)
    "key: $KeyFile (existing)"
} else {
    $p = New-Object System.Security.Cryptography.CngKeyCreationParameters
    $p.ExportPolicy = [System.Security.Cryptography.CngExportPolicies]::AllowPlaintextExport
    # no name: a key that lives only in this process (PowerShell would pass $null as "", a stored key)
    $key = [System.Security.Cryptography.CngKey]::Create([System.Security.Cryptography.CngAlgorithm]::ECDsaP256, [NullString]::Value, $p)
    New-Item -ItemType Directory -Force (Split-Path $KeyFile) | Out-Null
    $tmp = "$KeyFile.tmp"
    [IO.File]::WriteAllBytes($tmp, $key.Export($fmt::EccPrivateBlob))
    # this Windows user only: no inherited access, full control for the owner's SID
    $sid = [System.Security.Principal.WindowsIdentity]::GetCurrent().User.Value
    icacls $tmp /inheritance:r /grant:r "*${sid}:F" | Out-Null
    if ($LASTEXITCODE -ne 0) { Remove-Item $tmp -Force; throw "could not restrict access to $tmp" }
    Move-Item $tmp $KeyFile
    "key: $KeyFile (new: back it up somewhere safe and offline)"
}
$pub = $key.Export($fmt::EccPublicBlob) # BCRYPT_ECCPUBLIC_BLOB: magic ECS1, 32, X, Y
if ($pub.Length -ne 72) { throw "unexpected public key blob ($($pub.Length) bytes)" }
$rows = for ($i = 0; $i -lt 72; $i += 12) { "    " + (($pub[$i..($i + 11)] | ForEach-Object { "0x{0:X2}" -f $_ }) -join ", ") + "," }
$text = "// generated by tools/release_key.ps1 - the public half of the release signing key (BCRYPT_ECCPUBLIC_BLOB, ECDSA`n" +
        "// P-256): the launcher installs only releases whose SHA256SUMS.txt was signed with its private half`n" +
        "static const unsigned char k_release_key[72] = {`n" + ($rows -join "`n") + "`n};`n"
[IO.File]::WriteAllText($IncFile, $text, (New-Object Text.UTF8Encoding $false))
"public key: $IncFile"
